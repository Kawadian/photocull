export function formatDate(value: string, lang: Language, options: Intl.DateTimeFormatOptions) {
  return new Intl.DateTimeFormat(lang, { ...options, timeZone: 'UTC' }).format(
    new Date(value.length === 7 ? value + '-01' : value),
  )
}
