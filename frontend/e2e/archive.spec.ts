test('archive loading, disabled policy and recoverable service errors', async ({ page }) => {
  let release: () => void = () => {}
  const delay = new Promise<void>((resolve) => { release = resolve })
  await page.route('**/desktop/archive', async (route) => {
    await delay
    await route.continue()
  })
  await page.goto('/')
  await page.getByRole('navigation', { name: 'Library views' }).getByRole('button', { name: 'Archive', exact: true }).click()
  const archive = page.getByRole('main')
  await expect(archive.getByText('Loading…')).toBeVisible()
  release()
  await expect(archive.getByText(/No PHOTOCULL_WRITE_ROOTS directory covers this library/)).toBeVisible()
  await expect(archive.getByRole('button', { name: 'Preview operation' })).toBeDisabled()
  await expect(archive.getByRole('option', { name: 'Move to trash' })).toBeDisabled()
  await expect(archive.getByRole('option', { name: 'Batch rename' })).toBeDisabled()
  await archive.getByRole('combobox', { name: 'Action', exact: true }).selectOption('dng')
  await expect(archive.getByRole('option', { name: 'Replace originals after verification' })).toBeDisabled()
  await expect(archive.getByRole('option', { name: 'Export and trash verified originals' })).toBeDisabled()
  await page.route('**/desktop/archive/storage?*', (route) => route.fulfill({
    status: 503, json: { detail: 'Storage report temporarily unavailable' },
  }))
  await archive.getByRole('button', { name: 'Storage', exact: true }).click()
  await expect(archive.getByRole('alert')).toHaveText('Storage report temporarily unavailable')
  await page.unroute('**/desktop/archive/storage?*')
  await archive.getByRole('button', { name: 'Plan', exact: true }).click()
  await archive.getByRole('button', { name: 'Storage', exact: true }).click()
  await expect(archive.getByText('There is no indexed media yet.')).toBeVisible()
})

test('write access, saved preview-only rule, and verified overwrite on mobile', async ({ page, request }) => {
  test.setTimeout(50_000)
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/')
  await page.getByLabel('Library', { exact: true }).selectOption('archive')
  await page.getByRole('button', { name: 'Scan library' }).click()
  const library = '/api/libraries/archive'
  async function assets() {
    return ((await (await request.get(`${library}/assets?limit=20`)).json()).items as {
      id: number; path: string; rating: number; revision: number
    }[])
  }
  await expect.poll(async () => (await assets()).some((a) => a.path === 'zz-review.tiff')).toBe(true)
  const original = (await assets()).find((a) => a.path === 'zz-review.tiff')!
  const review = await request.patch(`${library}/assets/${original.id}/rating`, {
    data: { rating: 4, rejected: false, expected_revision: original.revision },
  })
  expect(review.ok()).toBeTruthy()
  await page.getByRole('navigation', { name: 'Library views' }).getByRole('button', { name: 'Archive', exact: true }).click()
  const archive = page.getByRole('main', { name: 'Archive' })
  const sections = archive.getByRole('navigation', { name: 'Archive sections' })
  await sections.getByRole('button', { name: 'Write access' }).click()
  await expect(archive.getByText('Self-test passed')).toBeVisible()
  await expect(archive.getByText(/Same mount/)).toBeVisible()
  await sections.getByRole('button', { name: 'Plan', exact: true }).click()
  await archive.getByRole('combobox', { name: 'Action', exact: true }).selectOption('jpeg')
  await archive.getByRole('combobox', { name: 'Destination', exact: true }).selectOption('overwrite')
  await archive.getByLabel('Asset IDs', { exact: true }).fill(String(original.id))
  await archive.getByRole('button', { name: 'Save as a rule' }).click()
  const rule = page.getByRole('dialog', { name: 'Save conversion rule' })
  await expect(rule.getByLabel('Preview interval in hours')).toHaveValue('0')
  await rule.getByLabel('Rule name').fill('Small archive candidates')
  await rule.getByRole('button', { name: 'Save rule' }).click()
  await expect(archive.getByText('Manual preview only', { exact: false })).toBeVisible()
  await archive.getByRole('button', { name: 'Prepare preview' }).click()
  await expect(archive.getByText('New preview · 1 eligible items')).toBeVisible()
  expect((await assets()).some((a) => a.path === 'zz-review.tiff')).toBe(true)
  await archive.getByRole('button', { name: 'Review latest preview' }).click()
  const preview = archive.getByRole('region', { name: 'Operation preview' })
  await expect(preview.getByText('Confirmation covers all eligible items across every page.')).toBeVisible()
  await preview.getByRole('button', { name: 'Review and confirm' }).click()
  const confirmation = page.getByRole('dialog', { name: 'JPEG' })
  await expect(confirmation.getByText(/1 item · .* of source media/)).toBeVisible()
  await expect(confirmation.getByText(/can be restored from Trash/)).toBeVisible()
  await confirmation.getByRole('button', { name: 'Confirm and queue' }).click()
  await expect.poll(async () => (await assets()).find((a) => a.path === 'zz-review.jpg'),
    { timeout: 20_000 }).toMatchObject({ id: original.id, rating: 4 })
  await sections.getByRole('button', { name: 'Trash', exact: true }).click()
  await expect(archive.getByText(/in trash/)).toBeVisible()
  await archive.getByLabel('Trash entries before (UTC)').fill('2099-01-01')
  await archive.getByRole('button', { name: 'Preview oldest-first purge' }).click()
  await preview.getByRole('button', { name: 'Review and confirm' }).click()
  const purge = page.getByRole('dialog', { name: 'Permanently delete' })
  await expect(purge.getByText(/cannot be undone/)).toBeVisible()
  await purge.getByRole('button', { name: 'Go back' }).click()
  await expect(purge).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(375)
})
